package org.schabi.newpipe.offline;

import android.content.Context;
import android.content.ContentResolver;
import android.net.Uri;

import org.junit.After;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;
import org.mockito.MockedStatic;

import java.io.ByteArrayInputStream;
import java.lang.reflect.Field;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.ExecutorService;

import static org.junit.Assert.assertEquals;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.doAnswer;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.mockStatic;
import static org.mockito.Mockito.when;

/** Real library importer with generated bytes; execution is held at its executor boundary. */
public class OfflineImportOwnershipTest {
    @Rule public final TemporaryFolder temporary = new TemporaryFolder();

    @After public void reset() throws Exception {
        final Field instance = OfflineLibrary.class.getDeclaredField("instance");
        instance.setAccessible(true);
        instance.set(null, null);
    }

    @Test public void networkOwnerRejectsStaleLocalRetryPreparation() throws Exception {
        final OfflineStore store = new OfflineStore(temporary.newFolder(), 1000);
        final var entry = store.beginDownload("Generated", "https://example.invalid/handoff",
                0, "video/mp4");
        org.junit.Assert.assertFalse("a stale local retry may not reset a network owner",
                store.prepareRetry(entry.id));
        assertEquals(OfflineStore.State.DOWNLOADING, store.get(entry.id).state);
        assertEquals("giga", store.get(entry.id).source);
    }

    @Test public void staleRetryLookupCannotResetANewlyCompletedSave() throws Exception {
        reset();
        final Context context = mock(Context.class);
        when(context.getApplicationContext()).thenReturn(context);
        when(context.getFilesDir()).thenReturn(temporary.getRoot());
        final OfflineLibrary library = OfflineLibrary.get(context);
        final OfflineStore actual = library.store();
        final OfflineStore.Entry entry = actual.create("Generated", "", 0,
                "file:///generated/race.wav", "audio/wav");
        final OfflineStore store = org.mockito.Mockito.spy(actual);
        final Field storeField = OfflineLibrary.class.getDeclaredField("store");
        storeField.setAccessible(true);
        storeField.set(library, store);
        // The old copier finishes between this retry's lookup and its ownership check.
        doAnswer(call -> {
            final OfflineStore.Entry stale = actual.get(entry.id);
            actual.copy(entry.id, new ByteArrayInputStream(new byte[]{1, 2, 3}));
            return stale;
        }).when(store).get(entry.id);
        final Field executorField = OfflineLibrary.class.getDeclaredField("copier");
        executorField.setAccessible(true);
        ((ExecutorService) executorField.get(library)).shutdown();
        final ExecutorService executor = mock(ExecutorService.class);
        executorField.set(library, executor);
        final Uri uri = mock(Uri.class);
        when(uri.getScheme()).thenReturn("file");
        try (MockedStatic<Uri> uris = mockStatic(Uri.class)) {
            uris.when(() -> Uri.parse(entry.source)).thenReturn(uri);
            library.retry(entry.id);
            assertEquals(OfflineStore.State.READY, actual.get(entry.id).state);
            assertEquals(3, actual.file(entry).length());
            org.mockito.Mockito.verify(executor, org.mockito.Mockito.never())
                    .execute(any(Runnable.class));
        }
    }

    @Test public void repeatedPendingAndReadyImportsOpenSourceOnlyOnce() throws Exception {
        reset();
        final Context context = mock(Context.class);
        when(context.getApplicationContext()).thenReturn(context);
        when(context.getFilesDir()).thenReturn(temporary.getRoot());
        final ContentResolver resolver = mock(ContentResolver.class);
        when(context.getContentResolver()).thenReturn(resolver);
        final Uri uri = mock(Uri.class);
        when(uri.getScheme()).thenReturn("file");
        when(uri.toString()).thenReturn("file:///generated/input.wav");
        when(resolver.openInputStream(uri)).thenReturn(
                new ByteArrayInputStream(new byte[]{1, 2, 3}));
        final OfflineLibrary library = OfflineLibrary.get(context);
        final Field executorField = OfflineLibrary.class.getDeclaredField("copier");
        executorField.setAccessible(true);
        ((ExecutorService) executorField.get(library)).shutdown();
        final ExecutorService executor = mock(ExecutorService.class);
        executorField.set(library, executor);
        final List<Runnable> pending = new ArrayList<>();
        doAnswer(call -> {
            pending.add(call.getArgument(0));
            return null;
        }).when(executor).execute(any(Runnable.class));
        try (MockedStatic<Uri> uris = mockStatic(Uri.class);
             MockedStatic<OfflineSaveNotifications> notices =
                     mockStatic(OfflineSaveNotifications.class)) {
            uris.when(() -> Uri.parse(uri.toString())).thenReturn(uri);
            final OfflineStore.Entry first = library.importUri(
                    uri, "Generated", "", 0, "audio/wav");
            final OfflineStore.Entry repeated = library.importUri(uri, "Again", "", 0, "audio/wav");
            assertEquals("only one copy job may own these bytes", 1, pending.size());
            assertEquals(first.id, repeated.id);
            pending.get(0).run();
            assertEquals(OfflineStore.State.READY, library.store().get(first.id).state);
            assertEquals(first.id, library.importUri(uri, "Ready", "", 0, "audio/wav").id);
            assertEquals(1, pending.size());
            org.mockito.Mockito.verify(resolver).openInputStream(uri);
        }
    }
}
