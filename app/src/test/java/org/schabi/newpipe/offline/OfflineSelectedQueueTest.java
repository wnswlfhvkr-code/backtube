package org.schabi.newpipe.offline;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import android.content.Context;

import org.junit.After;
import org.junit.Before;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;
import org.schabi.newpipe.R;
import org.schabi.newpipe.player.playqueue.OfflinePlayQueue;

import java.io.ByteArrayInputStream;
import java.lang.reflect.Field;
import java.util.List;
import java.util.stream.Collectors;

/** Actual owned-store/queue boundary; fixtures contain only generated bytes. */
public class OfflineSelectedQueueTest {
    @Rule public TemporaryFolder temporary = new TemporaryFolder();
    private OfflineLibrary library;
    private OfflineStore.Entry first;
    private OfflineStore.Entry second;
    private OfflineStore.Entry third;

    @Before public void setup() throws Exception {
        resetLibrary();
        final Context context = mock(Context.class);
        when(context.getApplicationContext()).thenReturn(context);
        when(context.getFilesDir()).thenReturn(temporary.getRoot());
        when(context.getString(R.string.offline_saved_copy)).thenReturn("Saved copy");
        library = OfflineLibrary.get(context);
        first = save("First");
        second = save("Second");
        third = save("Third");
    }

    @After public void teardown() throws Exception {
        resetLibrary();
    }

    @Test public void selectedSubsetDeduplicatesAndUsesFreshShelfOrderInsteadOfTapOrder()
            throws Exception {
        assertEquals(List.of(first.localUrl(), third.localUrl()),
                urls(library.queueSelected(List.of(third.id, first.id, third.id))));
        library.store().move(third.id, -2);
        final OfflinePlayQueue selected = library.queueSelected(List.of(first.id, third.id));
        assertEquals(List.of(third.localUrl(), first.localUrl()), urls(selected));
        assertEquals(0, selected.getIndex());
        assertTrue(selected.isOfflineOnly());
        assertTrue(selected.isComplete());
        selected.fetch();
        assertEquals(2, selected.size());
        library.store().move(first.id, -1);
        assertEquals(third.localUrl(), selected.getItem().getUrl());
    }

    @Test public void zeroUnknownDeletedMissingAndNonReadyNeverFallBackToAll() throws Exception {
        assertTrue(library.queueSelected(List.of()).isEmpty());
        assertTrue(library.queueSelected(List.of("unknown")).isEmpty());
        library.store().delete(first.id);
        assertTrue(library.store().file(second).delete());
        final OfflineStore.Entry pending = library.store().create("Pending", "", 0,
                "content://fixture/pending", "audio/wav");
        assertTrue(library.queueSelected(List.of(first.id, second.id, pending.id)).isEmpty());
        assertEquals(List.of(third.localUrl()), urls(library.queueAll()));
        assertEquals(List.of(third.localUrl()), urls(library.queueSelected(
                List.of(second.id, third.id, first.id, third.id))));
    }

    @Test public void selectedQueueKeepsExistingLocalMetadataAndFiniteTransitions()
            throws Exception {
        final OfflinePlayQueue selected = library.queueSelected(List.of(third.id, first.id));
        assertEquals(library.queue(first).getItem().getDuration(),
                selected.getItem().getDuration());
        assertEquals(first.serviceId, selected.getItem().getServiceId());
        library.store().delete(first.id);
        assertEquals(third.localUrl(), selected.transitionTarget(first.localUrl(),
                library.store(), false).getUrl());
        selected.pruneUnavailable(library.store(), true);
        assertEquals(List.of(third.localUrl()), urls(selected));
        assertEquals(List.of(second.localUrl(), third.localUrl()), urls(library.queueAll()));
    }

    private OfflineStore.Entry save(final String title) throws Exception {
        final OfflineStore.Entry item = library.store().create(title,
                "https://example.invalid/" + title, 0,
                "content://generated/" + title, "audio/wav");
        library.store().copy(item.id, new ByteArrayInputStream(new byte[20]));
        return library.store().get(item.id);
    }

    private static List<String> urls(final OfflinePlayQueue queue) {
        return queue.getStreams().stream().map(item -> item.getUrl()).collect(Collectors.toList());
    }

    private static void resetLibrary() throws Exception {
        final Field field = OfflineLibrary.class.getDeclaredField("instance");
        field.setAccessible(true);
        field.set(null, null);
    }
}
